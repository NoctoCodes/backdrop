#!/usr/bin/env python3
"""Backdrop's app icon, in the iOS / macOS 27 Liquid Glass style.

Rules it follows (Apple HIG "App icons", June 2026, and the iOS/macOS 27 icon refresh):
  - one simple idea, a few filled overlapping shapes, no photos, text or fine detail
  - a bold, full-bleed gradient background
  - glass built into the artwork: translucent layers that overlap, and where one lies over another
    the one behind shows through slightly bent (refraction between layers)
  - crisp edges (nothing feathered), less blur than 26
  - highlights subtle and fixed on top and bottom edges, not a diagonal glint
The idea: a wallpaper landscape, three glass waves under a glass sun.

usage: make_icon.py <out.svg>
"""
import math
import sys

S = 1024
TILE = (100, 100, 824)          # x, y, size of the squircle on the 1024 canvas (macOS grid)


def squircle(x, y, size, radius=0.2237):
    """Apple's tile: straight sides with continuous corners (curvature ramps in, no kink). Uses the
    widely used construction of Apple's rounded rect (two cubic curves per corner joined by a short
    line, with these fixed proportions of the radius), mirrored to all four corners."""
    r = size * radius
    # one corner, as offsets from its tile corner, from the top edge round to the right edge
    seg = [("L", [(-1.52866483, 0)]),
           ("C", [(-1.08849323, 0), (-0.86840689, 0), (-0.66993427, 0.06549600)]),
           ("L", [(-0.63149399, 0.07491100)]),
           ("C", [(-0.37282392, 0.16905899), (-0.16905899, 0.37282392), (-0.07491100, 0.63149399)]),
           ("L", [(-0.06549600, 0.66993427)]),
           ("C", [(0, 0.86840689), (0, 1.08849323), (0, 1.52866483)])]
    corners = [((x + size, y), (1, 1), False), ((x + size, y + size), (1, -1), True),
               ((x, y + size), (-1, -1), False), ((x, y), (-1, 1), True)]
    out = []
    for (cx, cy), (sx, sy), swap in corners:
        for cmd, pts in seg:
            q = []
            for dx, dy in pts:
                if swap:
                    dx, dy = -dy, -dx     # walk this corner from the vertical side to the horizontal
                q.append(f"{cx + sx * dx * r:.2f},{cy + sy * dy * r:.2f}")
            out.append(cmd + " ".join(q))
    return "M" + out[0][1:] + " " + " ".join(out[1:]) + " Z"


def disc(cx, cy, r):
    """The icon's shape: a circle, as Apple's round (watchOS / visionOS) icons."""
    return (f"M{cx - r},{cy} A{r},{r} 0 1 1 {cx + r},{cy} A{r},{r} 0 1 1 {cx - r},{cy} Z")


def wave(y0, amp, phase, tilt=0.0):
    """A band from a smooth wave top edge down past the bottom of the tile.
    Returns (fill path, top-edge path)."""
    x0, x1 = 60, 964
    pts = []
    for i in range(65):
        x = x0 + (x1 - x0) * i / 64
        u = (x - 512) / 412
        y = y0 + amp * math.sin(u * 2.4 + phase) + tilt * u * 60
        pts.append((x, y))
    top = "M" + " L".join(f"{x:.1f},{y:.1f}" for x, y in pts)
    fill = top + f" L{x1},1000 L{x0},1000 Z"
    return fill, top


def main(out):
    # round icon (the user's choice); squircle() is kept for a square variant
    tile = disc(512, 512, 430)
    # three waves, back to front: cool, violet-pink, warm (bold colours, as in 27)
    w_back, t_back = wave(545, 44, 0.6, tilt=-0.6)
    w_mid, t_mid = wave(628, 50, 2.3, tilt=0.5)
    w_front, t_front = wave(722, 38, 4.1, tilt=-0.3)
    sun = (600, 450, 130)       # cx, cy, r: setting behind the first wave

    def refracted(path, dx, dy, s=1.0):
        # the shape behind, as seen through the glass in front: nudged and slightly magnified
        return (f'<path d="{path}" transform="translate({dx} {dy}) translate(512 640) '
                f'scale({s}) translate(-512 -640)"')

    svg = f'''<svg xmlns="http://www.w3.org/2000/svg" width="{S}" height="{S}" viewBox="0 0 {S} {S}">
  <!-- Backdrop: generated by make_icon.py. iOS/macOS 27 Liquid Glass icon: bold background,
       layered glass waves with refraction between them, top/bottom edge highlights only. -->
  <defs>
    <clipPath id="tile"><path d="{tile}"/></clipPath>
    <clipPath id="cBack"><path d="{w_back}"/></clipPath>
    <clipPath id="cMid"><path d="{w_mid}"/></clipPath>
    <clipPath id="cFront"><path d="{w_front}"/></clipPath>
    <clipPath id="cSun"><circle cx="{sun[0]}" cy="{sun[1]}" r="{sun[2]}"/></clipPath>

    <linearGradient id="bg" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="#5B3BF2"/>
      <stop offset="0.55" stop-color="#3A1FB8"/>
      <stop offset="1" stop-color="#1A0D63"/>
    </linearGradient>
    <radialGradient id="bgGlow" cx="0.62" cy="0.34" r="0.55">
      <stop offset="0" stop-color="#B9A2FF" stop-opacity="0.55"/>
      <stop offset="1" stop-color="#B9A2FF" stop-opacity="0"/>
    </radialGradient>

    <linearGradient id="gBack" x1="0" y1="0" x2="1" y2="1">
      <stop offset="0" stop-color="#4FE3FF"/>
      <stop offset="1" stop-color="#2A5CFF"/>
    </linearGradient>
    <linearGradient id="gMid" x1="0" y1="0" x2="1" y2="0.6">
      <stop offset="0" stop-color="#FF3DB4"/>
      <stop offset="1" stop-color="#C21FE0"/>
    </linearGradient>
    <linearGradient id="gFront" x1="0" y1="0" x2="1" y2="0.4">
      <stop offset="0" stop-color="#FFB547"/>
      <stop offset="1" stop-color="#FF4F7B"/>
    </linearGradient>
    <radialGradient id="gSun" cx="0.38" cy="0.32" r="0.8">
      <stop offset="0" stop-color="#FFFFFF" stop-opacity="1"/>
      <stop offset="0.55" stop-color="#FFF0C4" stop-opacity="0.97"/>
      <stop offset="1" stop-color="#FFC970" stop-opacity="0.95"/>
    </radialGradient>
    <!-- glass sheen: light enters from the top -->
    <linearGradient id="sheen" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="#FFFFFF" stop-opacity="0.26"/>
      <stop offset="0.25" stop-color="#FFFFFF" stop-opacity="0.04"/>
      <stop offset="1" stop-color="#FFFFFF" stop-opacity="0"/>
    </linearGradient>
    <linearGradient id="tileTop" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="#FFFFFF" stop-opacity="0.55"/>
      <stop offset="0.08" stop-color="#FFFFFF" stop-opacity="0"/>
      <stop offset="0.92" stop-color="#FFFFFF" stop-opacity="0"/>
      <stop offset="1" stop-color="#FFFFFF" stop-opacity="0.22"/>
    </linearGradient>
  </defs>

  <g clip-path="url(#tile)">
    <!-- background -->
    <rect x="0" y="0" width="{S}" height="{S}" fill="url(#bg)"/>
    <rect x="0" y="0" width="{S}" height="{S}" fill="url(#bgGlow)"/>

    <!-- sun: a glass disc, the background bent inside it -->
    <circle cx="{sun[0]}" cy="{sun[1]}" r="{sun[2]}" fill="url(#gSun)"/>
    <g clip-path="url(#cSun)">
      <rect x="0" y="0" width="{S}" height="{S}" fill="url(#bgGlow)" opacity="0.5"
            transform="translate({sun[0]} {sun[1]}) scale(1.25) translate({-sun[0]} {-sun[1]})"/>
    </g>
    <circle cx="{sun[0]}" cy="{sun[1]}" r="{sun[2] - 2}" fill="none" stroke="#FFFFFF" stroke-opacity="0.7" stroke-width="4"/>

    <!-- back wave -->
    <path d="{w_back}" fill="url(#gBack)" fill-opacity="0.94"/>
    <g clip-path="url(#cBack)" opacity="0.45">
      <circle cx="{sun[0] + 8}" cy="{sun[1] + 16}" r="{sun[2] * 1.06}" fill="url(#gSun)"/>
    </g>
    <path d="{w_back}" fill="url(#sheen)"/>
    <path d="{t_back}" fill="none" stroke="#FFFFFF" stroke-opacity="0.75" stroke-width="5" stroke-linecap="round"/>

    <!-- middle wave; the back wave seen through it, bent -->
    <path d="{w_mid}" fill="url(#gMid)" fill-opacity="0.95"/>
    <g clip-path="url(#cMid)" opacity="0.18">
      {refracted(w_back, 10, 14, 1.04)} fill="url(#gBack)"/>
    </g>
    <path d="{w_mid}" fill="url(#sheen)"/>
    <path d="{t_mid}" fill="none" stroke="#FFFFFF" stroke-opacity="0.8" stroke-width="5" stroke-linecap="round"/>

    <!-- front wave; both behind it seen through it, bent -->
    <path d="{w_front}" fill="url(#gFront)" fill-opacity="0.97"/>
    <g clip-path="url(#cFront)" opacity="0.34">
      {refracted(w_mid, -12, 16, 1.05)} fill="url(#gMid)"/>
    </g>
    <path d="{w_front}" fill="url(#sheen)"/>
    <path d="{t_front}" fill="none" stroke="#FFFFFF" stroke-opacity="0.85" stroke-width="5" stroke-linecap="round"/>

    <!-- tile edge light, top and bottom only -->
    <path d="{tile}" fill="url(#tileTop)" opacity="0.6"/>
  </g>
  <path d="{tile}" fill="none" stroke="#FFFFFF" stroke-opacity="0.18" stroke-width="3"/>
</svg>
'''
    with open(out, "w") as f:
        f.write(svg)


if __name__ == "__main__":
    main(sys.argv[1])
